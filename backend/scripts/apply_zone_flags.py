def norm(d):
    # 행정동(숫자+동) → 법정동. 단 'N가'는 보존.
    m = re.match(r"^(.+?)\d+동$", d)
    return (m.group(1) + "동") if m and not d.endswith("가") else d

# (gu, 법정동) → (program, name) 매핑
zmap = {}
for gu, dong, prog, name in ZONES:
    zmap.setdefault((gu, norm(dong)), (prog, name))

fp = ROOT / "data" / "building_age.json"
data = json.loads(fp.read_text(encoding="utf-8"))
flipped = 0
for d in data["dongs"]:
    key = (d["gu"], d["dong"])
    if key in zmap and not d.get("already_zone"):
        d["already_zone"] = True
        d["zone_program"], d["zone_name"] = zmap[key]
        flipped += 1
    elif d.get("already_zone") and "zone_program" not in d:
        d["zone_program"] = "정비구역"; d["zone_name"] = ""
    # verdict 재계산 (already_zone 반영)
    nv = d.get("nohu", 0)
    d["verdict"] = ("진행중" if d.get("already_zone")
                    else "후보" if nv >= 60 else "경계" if nv >= 45 else "신축위주")

fp.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
total_zone = len([x for x in data["dongs"] if x.get("already_zone")])
print(f"신규 플래그(미지정→진행중): {flipped}개 동")
print(f"전체 진행중(already_zone): {total_zone} / {len(data['dongs'])}")
print(f"미지정 후보(verdict=후보): {len([x for x in data['dongs'] if x['verdict']=='후보'])}")
